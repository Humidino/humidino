#pragma once
#include <cstdint>

#include "settings_store.h"

// Автоматическая сезонная подстройка порогов осушения — профили подобраны
// под климат Лотошино, Московская область (умеренно континентальный: снежная
// зима со средними -8..-10°C и морозами глубже -30°C, выраженное весеннее
// снеготаяние, тёплое влажное лето с ливнями, дождливая осень перед
// промерзанием грунта). Полное обоснование каждого числа — в
// docs/SEASONAL_LOTOSHINO.md; здесь только код.
//
// Работает поверх системного времени (time_sync.h): без NTP-синхронизации
// сезон не определить, поэтому до первой синхронизации автоподстройка молчит
// и не трогает текущие пороги — устройство продолжает работать с тем, что
// уже сохранено в NVS (см. seasonTask в season.cpp).
namespace Season {

enum class Id : uint8_t { Winter, Spring, Summer, Autumn };

// Машиночитаемый идентификатор (для JSON-API) — "winter"/"spring"/"summer"/"autumn".
const char* toString(Id season);

// Календарный месяц (1-12, локальный) -> сезон.
// Зима: дек-фев, весна: мар-май, лето: июн-авг, осень: сен-ноя.
Id forLocalMonth(int month1to12);

// Сезон на момент данной unix-эпохи (UTC), с учётом LOCAL_TZ_OFFSET_SEC
// (config.h) — тот же сдвиг, что уже используется для группировки
// календарных дней в run_log.h/telemetry.cpp.
Id forEpoch(uint32_t utcEpoch);

// Пороги/тайминги, подобранные под этот сезон именно для Лотошино/МО.
// Возвращает осмысленную отправную точку, а не измеренную калибровку
// конкретного подпола — см. docs/SEASONAL_LOTOSHINO.md.
Settings::PresetValues profileFor(Id season);

// Последний определённый сезон (кэш, обновляется фоновой задачей). До первой
// успешной NTP-синхронизации после старта возвращает Winter как безопасное
// умолчание (не используется ни для чего, кроме отображения на дашборде —
// на пороги до синхронизации это не влияет, см. комментарий выше).
Id current();

// Запускает фоновую задачу (см. begin() в .cpp): каждые несколько минут
// проверяет текущий локальный сезон и, если он сменился с прошлой проверки
// (в том числе один раз сразу после каждой перезагрузки, как только время
// синхронизируется) и включена RuntimeSettings::seasonAutoEnabled —
// подставляет profileFor() через SettingsActions::applyRuntimeSettings().
void begin();

}  // namespace Season
