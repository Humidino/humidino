#pragma once
#include <cstdint>

// Синхронизация времени по NTP — нужна только для того, чтобы записи в
// журнале запусков (run_log.h) несли реальную дату/время, а не только
// миллисекунды с загрузки. Без выхода в интернет (изолированная локальная
// сеть) синхронизация не пройдёт — журнал продолжит работать как обычно,
// просто новые записи будут получать эпоху 0 ("время не синхронизировано"),
// как и до подключения.
namespace TimeSync {

// Запускает SNTP-клиент (однократно, повторные вызовы — no-op) — вызывать
// после успешного подключения к WiFi. Сама синхронизация асинхронная и
// занимает какое-то время; готовность проверяется через isSynced()/nowEpoch().
void begin();

bool isSynced();

// Unix-эпоха (UTC), 0 — если время ещё не синхронизировано.
uint32_t nowEpoch();

}  // namespace TimeSync
