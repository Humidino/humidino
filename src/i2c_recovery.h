#pragma once
#include <Wire.h>
#include <cstdint>

// Стандартная последовательность разблокировки шины I2C на случай, если
// ведомое устройство держит SDA в LOW (например, сброс посреди транзакции,
// просадка питания) и аппаратный контроллер I2C больше не может завершить
// транзакцию. Работает через обычный GPIO — блокирует не дольше нескольких
// сотен микросекунд.
namespace I2CRecovery {

// Общая часть восстановления — голый bit-bang на пинах, без привязки к
// конкретному классу шины: до 9 тактов SCL, чтобы зависший на SDA=LOW
// ведомый успел отпустить линию, затем ручной STOP. Используется и для
// аппаратных шин (см. recoverBus ниже), и для программных (bit-bang) шин
// SoftI2C на I2C2/I2C3 — см. sensors.cpp. Возвращает true, если после этого
// SDA отпущена (в состоянии покоя HIGH).
bool unstickPins(uint8_t sdaPin, uint8_t sclPin);

// Завершает работу `bus`, вызывает unstickPins(), затем заново
// инициализирует `bus` на указанных пинах/частоте.
bool recoverBus(TwoWire& bus, uint8_t sdaPin, uint8_t sclPin, uint32_t clockHz);

}  // namespace I2CRecovery
