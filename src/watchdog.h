#pragma once

// Тонкая обёртка над esp_task_wdt, чтобы все долгоживущие задачи
// регистрировались единообразно. Инициализируется один раз в main.cpp до
// создания любых задач; каждая задача вызывает Watchdog::registerCurrentTask()
// в начале своей функции и Watchdog::feed() раз за итерацию цикла.
namespace Watchdog {

void begin();
void registerCurrentTask();
void feed();

// Снимает текущую задачу с watchdog на время заведомо долгой блокирующей
// операции без штатного цикла feed() (например, интерактивная калибровка
// тачскрина, ждущая касания пользователя) — иначе таймаут WDT_TIMEOUT_S
// перезагрузит устройство прямо посреди калибровки. Парная функция —
// registerCurrentTask() — возвращает задачу под наблюдение после.
void unregisterCurrentTask();

}  // namespace Watchdog
