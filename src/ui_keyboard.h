#pragma once
#include <lvgl.h>

// Один общий экранный клавиатурный виджет, которым пользуются все поля
// ввода текста тач-интерфейса (например, имя пресета).
// Создаётся один раз поверх корневого экрана (см. ui_root.cpp) и всплывает
// поверх текущей вкладки при фокусе на любом привязанном textarea —
// отдельная клавиатура на каждом экране не нужна.
namespace UiKeyboard {

void init(lv_obj_t* rootLayer);

// Подписывает textarea на получение фокуса: касание поля поднимает общую
// клавиатуру и привязывает её к этому полю.
void bindFocus(lv_obj_t* textarea);

// Принудительно прячет клавиатуру и снимает фокус с привязанного поля —
// нужно экранам, у которых есть своя кнопка "Отмена"/переход назад, а не
// только штатные кнопки самой клавиатуры (Ok/Cancel).
void hide();

}  // namespace UiKeyboard
