#pragma once
#include <cstdint>

// ШИМ-подсветка (GPIO2) с гашением по бездействию. В этой конструкции нет
// сенсорной панели, поэтому «активностью» считается смена состояния реле
// (реальное системное событие), а не действие пользователя — экран
// возвращается к полной яркости при каждом значимом событии, а затем
// плавно гаснет до приглушённого, но читаемого уровня через
// BACKLIGHT_DIM_TIMEOUT_MS мс без такого события.
namespace Backlight {

void begin();
void setLevel(uint8_t pct);   // 0-100 %, немедленно (без плавного перехода)
void noteActivity();          // вызывать при смене состояния реле
void update(uint32_t nowMs);  // вызывать на каждом тике lvglTask; ведёт плавный переход

}  // namespace Backlight
