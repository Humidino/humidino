#pragma once

// Чистая математика климата, не зависящая от железа. Нет зависимости от
// Arduino, поэтому её можно юнит-тестировать в нативном окружении PlatformIO
// (pio test -e native).
namespace ClimateMath {

// Точка росы по приближению Магнуса-Тетенса (a=17.62, b=243.12 °C),
// корректно для 0..60°C / 1..100% отн. влажности (достаточно для диапазона
// этого приложения).
float dewPointC(float tempC, float rhPercent);

// Абсолютная влажность в г/м³ по температуре и относительной влажности,
// выведена из давления насыщенного пара (Магнус) и уравнения состояния
// идеального газа для водяного пара.
float absHumidityGm3(float tempC, float rhPercent);

}  // namespace ClimateMath
