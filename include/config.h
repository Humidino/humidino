#pragma once
#include <cstdint>

// ============================================================================
// Дисплей (ILI9488 480x320, SPI) — физические пины SPI/сброса, а также
// TOUCH_CS тачскрина XPT2046 (делит SPI-шину с дисплеем, см. User_Setup.h),
// заданы в include/tft_config/User_Setup.h и потребляются только самой
// TFT_eSPI. Здесь дублируется только подсветка — ей отдельно рулит ledc в
// backlight.cpp, а не TFT_eSPI.
// ============================================================================
constexpr uint8_t PIN_TFT_BACKLIGHT = 2;

// ============================================================================
// Шина I2C 0: датчики подпола (Wire)
// ============================================================================
constexpr uint8_t PIN_I2C0_SDA = 21;
constexpr uint8_t PIN_I2C0_SCL = 18;

// ============================================================================
// Шина I2C 1: улица + средняя зона подпола, Зона 2 (Wire1)
// ============================================================================
constexpr uint8_t PIN_I2C1_SDA = 47;
constexpr uint8_t PIN_I2C1_SCL = 48;

constexpr uint8_t SHT31_ADDR_A = 0x44;
constexpr uint8_t SHT31_ADDR_B = 0x45;
constexpr uint32_t I2C_CLOCK_HZ = 10000;
constexpr uint16_t I2C_TRANSACTION_TIMEOUT_MS = 50;  // мс — таймаут одной I2C-транзакции (Wire.setTimeOut)

// ============================================================================
// Реле (SSR)
// ============================================================================
constexpr uint8_t PIN_RELAY_SSR = 17;
constexpr bool RELAY_ACTIVE_HIGH = true;

// ============================================================================
// Идентификаторы датчиков — по одному датчику SHT-30 на каждой из двух шин
// I2C (подпол и улица).
// ============================================================================
enum class SensorId : uint8_t {
    CrawlspaceIntake = 0,  // шина0, адрес 0x44 — подпол
    Outside          = 1,  // шина1, адрес 0x44 — улица
    Count            = 2
};

// ============================================================================
// Тайминги
// ============================================================================
constexpr uint32_t SENSOR_POLL_INTERVAL_MS  = 3000;  // 3000 мс = 3 с — период опроса датчиков
constexpr uint8_t  MOVING_AVG_WINDOW        = 5;      // окно скользящего среднего, отсчётов
constexpr uint8_t  I2C_FAILURE_RECOVERY_THRESHOLD = 3;  // подряд неудач до восстановления шины
constexpr uint32_t SENSOR_OFFLINE_RETRY_MS  = 60UL * 1000;  // 60 с — как часто переопрашивать датчик,
                                                             // который не отвечает даже после восстановления шины
                                                             // (например, физически не подключён)

constexpr uint32_t CONTROL_EVAL_INTERVAL_MS = 1000;   // 1000 мс = 1 с — период оценки состояния реле
constexpr uint32_t MIN_RUNTIME_MS           = 10UL * 60 * 1000;  // 10 мин минимальной работы
constexpr uint32_t MIN_PAUSE_MS             = 15UL * 60 * 1000;  // 15 мин минимальной паузы

constexpr float DEFAULT_RH_TARGET_PERCENT   = 70.0f;  // % — порог влажности подпола
constexpr float DEFAULT_HYSTERESIS_PERCENT  = 5.0f;   // % — гистерезис по влажности
constexpr float FREEZE_PROTECT_TEMP_C       = 2.0f;   // °C — защита от замерзания

constexpr uint32_t WDT_TIMEOUT_S            = 8;  // с — таймаут аппаратного watchdog

constexpr uint32_t BACKLIGHT_DIM_TIMEOUT_MS = 5UL * 60 * 1000;  // 5 мин бездействия до гашения
constexpr uint32_t BACKLIGHT_FADE_MS        = 1500;  // 1500 мс = 1,5 с — длительность плавного гашения
constexpr uint8_t  BACKLIGHT_FULL_PCT       = 100;    // % яркости в рабочем режиме
constexpr uint8_t  BACKLIGHT_DIM_PCT        = 15;     // % яркости в приглушённом режиме

// ============================================================================
// Сеть
// ============================================================================
constexpr uint16_t WEB_SERVER_PORT          = 80;
constexpr const char* DEVICE_HOSTNAME       = "humidino";

// ============================================================================
// Журнал запусков реле / аналитика (src/run_log.h, src/time_sync.h)
// ============================================================================
// Записей в кольцевом буфере на LittleFS (~48 байт/запись => ~96 КБ при
// максимуме — раздел littlefs на 8/16 МБ флеша это не заметит). При типичной
// частоте циклов (мин. пауза 15 мин => максимум ~57 циклов/сутки) этого
// хватает на несколько недель-месяцев истории.
constexpr uint32_t RUN_LOG_CAPACITY = 2000;

// Смещение локального часового пояса от UTC, секунды. Время в журнале и
// JSON-API всегда UTC (эпоха Unix); это смещение используется только для
// группировки "сегодня" в сводке статистики и для часов на экране платы —
// веб-интерфейс сам переводит эпоху в локальное время браузера и это
// смещение не использует. По умолчанию МСК (UTC+3) — поменяйте под свой
// часовой пояс, если устройство стоит не в этом поясе.
constexpr int32_t LOCAL_TZ_OFFSET_SEC = 3 * 3600;
