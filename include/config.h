// ============================================================================
// Дисплей (ILI9488 480x320, SPI) — физические пины SPI/сброса, а также
// TOUCH_CS тачскрина XPT2046 (делит SPI-шину с дисплеем, см. User_Setup.h),
// заданы в include/tft_config/User_Setup.h и потребляются только самой
// TFT_eSPI. Здесь дублируется только подсветка — ей отдельно рулит ledc в
// backlight.cpp, а не TFT_eSPI.
// ============================================================================
constexpr uint8_t PIN_TFT_BACKLIGHT = 2;

// ============================================================================
// 4 датчика SHT-30, по одному на своей независимой шине I2C — ни одна шина
// не делится между двумя датчиками (см. docs/WIRING.md §3 про то, почему).
// Физически провода идут двумя связками (по 2 датчика на каждой, см.
// docs/WIRING.md §3.5): связка 1 — приточка + середина подпола (I2C0+I2C2),
// связка 2 — дальний угол подпола + улица (I2C3+I2C1).
//
// У ESP32-S3 только 2 аппаратных контроллера I2C (Wire/Wire1) — их занимают
// шины I2C0 и I2C1. Для оставшихся двух датчиков (I2C2, I2C3) аппаратных
// контроллеров больше нет, поэтому шина реализована программно (bit-bang,
// см. soft_i2c.h) на произвольных свободных GPIO — с точки зрения датчика
// это обычный I2C на подтянутых резисторами линиях, разница только в том,
// что ESP32-S3 бит-банжит протокол сам, а не через выделенный контроллер.
// ============================================================================

// Шина I2C 0 (аппаратная, Wire) — датчик подпола у приточки.
constexpr uint8_t PIN_I2C0_SDA = 21;
constexpr uint8_t PIN_I2C0_SCL = 18;

// Шина I2C 1 (аппаратная, Wire1) — датчик улицы.
constexpr uint8_t PIN_I2C1_SDA = 47;
constexpr uint8_t PIN_I2C1_SCL = 8;

// Шина I2C 2 (программная, SoftI2C) — датчик подпола, середина.
constexpr uint8_t PIN_I2C2_SDA = 4;
constexpr uint8_t PIN_I2C2_SCL = 5;

// Шина I2C 3 (программная, SoftI2C) — датчик подпола, дальний угол.
constexpr uint8_t PIN_I2C3_SDA = 6;
constexpr uint8_t PIN_I2C3_SCL = 7;

// Все датчики — SHT-30 на адресе 0x44 (ADDR подключён к GND). Второй адрес
// (ADDR подключён к VDD) в прошивке не используется ни одним датчиком — он
// только сканируется на каждой шине при старте (см. scanBus() в sensors.cpp)
// как диагностика: если на шине неожиданно отвечает 0x45, значит перепутана
// разводка ADDR у конкретного модуля.
constexpr uint8_t SHT31_ADDR_A = 0x44;
constexpr uint8_t SHT31_ADDR_B = 0x45;
constexpr uint32_t I2C_CLOCK_HZ = 10000;
constexpr uint32_t SOFT_I2C_CLOCK_HZ = 10000;  // та же частота, что и на аппаратных шинах — тоже длинные провода
constexpr uint16_t I2C_TRANSACTION_TIMEOUT_MS = 50;  // мс — таймаут одной I2C-транзакции (Wire.setTimeOut)

// ============================================================================
// Реле (SSR)
// ============================================================================
constexpr uint8_t PIN_RELAY_SSR = 17;
constexpr bool RELAY_ACTIVE_HIGH = true;

// ============================================================================
// Идентификаторы датчиков — по одному датчику SHT-30 на каждой из четырёх
// независимых шин I2C. В алгоритме осушения (relay.cpp) участвуют только
// CrawlspaceIntake и Outside — CrawlspaceMid/CrawlspaceFar чисто
// информационные (дашборд/веб), решение о включении вытяжки не меняют.
// ============================================================================
enum class SensorId : uint8_t {
    CrawlspaceIntake = 0,  // шина I2C0 (аппаратная), адрес 0x44 — подпол у приточки
    CrawlspaceMid    = 1,  // шина I2C2 (программная), адрес 0x44 — подпол, середина
    CrawlspaceFar    = 2,  // шина I2C3 (программная), адрес 0x44 — подпол, дальний угол
    Outside          = 3,  // шина I2C1 (аппаратная), адрес 0x44 — улица
    Count            = 4
};

// true для любого из датчиков подпола (Zone1..Zone3), false для Outside —
// единая точка правды для кода, которому нужно отличать роль датчика, а не
// конкретную зону (агрегация в relay.cpp, разметка UI в ui_dashboard.cpp).
constexpr bool isCrawlspaceSensor(SensorId id) {
    return id != SensorId::Outside;
}

// Сколько датчиков подпола физически ожидается — используется для индикации
// деградированной работы (RelayStatus::crawlspaceLiveSensors в
// shared_state.h: X из CRAWLSPACE_SENSOR_COUNT датчиков сейчас живы).
constexpr uint8_t CRAWLSPACE_SENSOR_COUNT = static_cast<uint8_t>(SensorId::Count) - 1;

